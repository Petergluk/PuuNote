export const DEFAULT_SYSTEM_PROMPT = 'Твоя задача — преобразовать линейный текст в иерархическую древовидную структуру. Это необходимо для того, чтобы пользователь мог нелинейно перемещаться по материалу. Раздели текст на логические блоки, темы или хронологические этапы и выстрой их в виде вложенного горизонтального дерева.';

export function buildSmartImportPrompt(options: {
  systemPrompt?: string;
  detailLevel: string;
  maxDepth: number;
  customPrompt: string;
  text: string;
}) {
  let baseInstructions = options.systemPrompt || DEFAULT_SYSTEM_PROMPT;

  if (options.detailLevel === 'full') {
      baseInstructions += `\nПолный импорт: перенеси предоставленный текст в структуру без сокращений. Сохрани весь исходный объем информации, распределив его по узлам дерева.`;
  } else if (options.detailLevel === 'optimized') {
      baseInstructions += `\nОптимизированный импорт: сохрани всю фактологию и структуру, удаляя только явные повторы и смысловые дубликаты.`;
  } else if (options.detailLevel === 'brief') {
      baseInstructions += `\nКраткий импорт: оставь только ключевые темы и тезисы (выжимку), опуская мелкие детали.`;
  }

  if (options.maxDepth > 0) {
    baseInstructions += `\nОграничение: Максимальная глубина вложенности дерева: ${options.maxDepth}.`;
  }

  if (options.customPrompt) {
    baseInstructions += `\nДополнительные инструкции от пользователя:\n${options.customPrompt}\n`;
  }

  return `${baseInstructions}
        
Формат ответа: древовидный вложенный JSON-массив объектов. Каждый объект должен иметь поле 'title' (строка с текстом узла, можно использовать markdown форматирование внутри строки) и опционально массив 'children' (дочерние объекты такой же структуры).

Важно: если пользователь указал дополнительные инструкции (prompt), они имеют приоритет при формировании уровней и структуры дерева.
В противном случае (по умолчанию), сделай так, чтобы у корня были верхнеуровневые темы или разделы, а дальше они древовидно разворачивались вглубь конкретными блоками текста.

Текст для импорта:
${options.text}

Ответь ТОЛЬКО валидным JSON-массивом. Не добавляй никаких других слов (например, \`\`\`json) вокруг массива.`;
}
